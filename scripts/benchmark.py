"""Part 3 benchmark: exact brute force vs FAISS HNSW, at the real size and synthetically scaled.

Larger catalogues are simulated by jittering the real 30k weighted vectors (Gaussian noise,
then re-scaled per block via the same norms). That preserves the real data's cluster
structure, which matters a lot for ANN behaviour, unlike i.i.d. random vectors.

    uv run python scripts/benchmark.py --scales 30000 300000 1000000
"""

from __future__ import annotations

import argparse
import time
from pathlib import Path

import numpy as np
import pandas as pd

from similarity.config import Settings
from similarity.engine import SimilarityEngine
from similarity.index import ExactIndex, HnswIndex


def recall_at_k(truth: np.ndarray, got: np.ndarray) -> float:
    return float(np.mean([len(set(t) & set(g)) / len(t) for t, g in zip(truth, got, strict=True)]))


def latency_ms(index, Q: np.ndarray, k: int) -> tuple[float, float]:
    """Single-query latency (the API serves one product per request)."""
    times = []
    for q in Q:
        t0 = time.perf_counter()
        index.search(q[None, :], k)
        times.append((time.perf_counter() - t0) * 1e3)
    return float(np.percentile(times, 50)), float(np.percentile(times, 99))


def scale_up(X: np.ndarray, n: int, rng: np.random.Generator, noise: float = 0.02) -> np.ndarray:
    if n <= len(X):
        return X[:n]
    base = X[rng.integers(0, len(X), n - len(X))]
    jitter = rng.standard_normal(base.shape).astype(np.float32) * noise
    jitter[base == 0] = 0  # keep missing blocks missing
    return np.vstack([X, base + jitter]).astype(np.float32)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--scales", nargs="+", type=int, default=[30_000, 300_000])
    ap.add_argument("--queries", type=int, default=300)
    ap.add_argument("--k", type=int, default=10)
    ap.add_argument("--ef", nargs="+", type=int, default=[16, 32, 64, 128])
    ap.add_argument("--out", type=Path, default=Path("reports/benchmark.md"))
    args = ap.parse_args()

    settings = Settings(backend="exact")
    X0 = SimilarityEngine.load(settings).vectors
    rng = np.random.default_rng(0)
    rows = []
    for n in args.scales:
        X = scale_up(X0, n, rng)
        Q = X[rng.choice(n, args.queries, replace=False)]
        exact = ExactIndex(X)
        _, truth = exact.search(Q, args.k)
        p50, p99 = latency_ms(exact, Q, args.k)
        mem = X.nbytes / 2**20
        rows.append({"N": n, "index": "exact (brute force)", "efSearch": "-", "recall@10": 1.0,
                     "p50 ms": p50, "p99 ms": p99, "build s": 0.0, "memory MiB": mem})
        print(f"N={n:>9,} exact p50={p50:.2f}ms")

        metrics = ["ip", "l2"] if n == args.scales[0] else ["ip"]
        for metric in metrics:
            t0 = time.perf_counter()
            hnsw = HnswIndex.build(X, m=settings.hnsw_m, ef_construction=settings.hnsw_ef_construction, metric=metric)
            build_s = time.perf_counter() - t0
            # FAISS HNSW stores the flat vectors plus ~2*M int32 neighbour ids per vector on level 0.
            graph_mib = n * 2 * settings.hnsw_m * 4 / 2**20
            for ef in args.ef:
                hnsw.ef_search = ef
                _, got = hnsw.search(Q, args.k)
                p50, p99 = latency_ms(hnsw, Q, args.k)
                rows.append({"N": n, "index": f"HNSW M={settings.hnsw_m} ({metric})", "efSearch": ef,
                             "recall@10": recall_at_k(truth, got), "p50 ms": p50, "p99 ms": p99,
                             "build s": build_s, "memory MiB": mem + graph_mib})
                print(f"N={n:>9,} hnsw[{metric}] ef={ef:<4} recall={rows[-1]['recall@10']:.4f} p50={p50:.3f}ms")

    df = pd.DataFrame(rows)
    table = df.to_markdown(index=False, floatfmt=".3f")
    print("\n" + table)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        f"# Benchmark: exact vs HNSW\n\nd={X0.shape[1]}, k={args.k}, {args.queries} single-vector queries per row, "
        f"single thread-pool default. Scales above 30k are the real vectors jittered (see script).\n"
        f"Generated by `scripts/benchmark.py`.\n\n{table}\n"
    )
    print(f"written to {args.out}")


if __name__ == "__main__":
    main()
